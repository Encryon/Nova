def _model_class_name(entity: Entity) -> str:
    return to_pascal_case(entity.name)


def _table_name(entity: Entity) -> str:
    return to_snake_case(pluralize(to_ascii_identifier(entity.name)))


def _field_line(entity: Entity, f) -> str:
    if not f.is_reference:
        py_type = PY_TYPE_MAP.get(f.type, "str")
        type_hint = py_type if f.required else f"Optional[{py_type}]"
        opts = []
        if f.unique:
            opts.append("unique=True")
        if f.pattern:
            opts.append(f'pattern=r"{f.pattern}"')
        if f.default is not None:
            opts.append(f"default={f.default!r}")
        elif not f.required:
            opts.append("default=None")
        opts_str = ", ".join(opts)
        suffix = f" = Field({opts_str})" if opts_str else ""
        return f"    {to_snake_case(f.name)}: {type_hint}{suffix}"
    else:
        # Référence vers une autre entité : clé étrangère simple sur son id.
        target_table = to_snake_case(pluralize(to_ascii_identifier(f.type)))
        return (
            f"    {to_snake_case(f.name)}_id: Optional[int] = "
            f'Field(default=None, foreign_key="{target_table}.id")'
        )


def _generate_models(program: NovaProgram) -> str:
    lines = [
        _HEADER,
        "from __future__ import annotations",
        "",
        "from datetime import date, datetime",
        "from typing import Optional",
        "",
        "from sqlmodel import Field, SQLModel",
        "",
        "",
    ]
    for entity in program.entities:
        cls = _model_class_name(entity)
        table = _table_name(entity)
        lines.append(f"class {cls}(SQLModel, table=True):")
        lines.append(f'    """Généré depuis `entity {entity.name}` / `entité {entity.name}`."""')
        lines.append(f'    __tablename__ = "{table}"')
        lines.append("")
        lines.append("    id: Optional[int] = Field(default=None, primary_key=True)")
        for f in entity.fields:
            lines.append(_field_line(entity, f))
        for rel in entity.relations:
            if rel.kind == "belongs_to":
                target_table = to_snake_case(pluralize(to_ascii_identifier(rel.target)))
                lines.append(
                    f"    {to_snake_case(rel.target)}_id: Optional[int] = "
                    f'Field(default=None, foreign_key="{target_table}.id")'
                )
            else:  # has_many -> informational, pas de colonne sur cette table
                lines.append(f"    # has_many / possède_plusieurs {rel.target} -> voir la table {to_snake_case(pluralize(to_ascii_identifier(rel.target)))}")
        lines.append("")
        lines.append("")

        # Schémas Create/Update/Read séparés du modèle table pour une API propre.
        # Les relations belongs_to sont exposées comme de simples clés étrangères
        # (<cible>_id) : c'est ce qui permet de rattacher un enregistrement à un
        # parent via l'API (sinon la relation serait indisponible en écriture).
        fk_field_names = [to_snake_case(rel.target) + "_id" for rel in entity.relations if rel.kind == "belongs_to"]

        lines.append(f"class {cls}Create(SQLModel):")
        body = [f for f in entity.fields]
        if not body and not fk_field_names:
            lines.append("    pass")
        for f in body:
            py_type = PY_TYPE_MAP.get(f.type, "str") if not f.is_reference else "int"
            type_hint = py_type if f.required else f"Optional[{py_type}]"
            if f.pattern:
                kwargs = f'pattern=r"{f.pattern}"' if f.required else f'default=None, pattern=r"{f.pattern}"'
                lines.append(f"    {to_snake_case(f.name)}: {type_hint} = Field({kwargs})")
            else:
                default = "" if f.required else " = None"
                lines.append(f"    {to_snake_case(f.name)}: {type_hint}{default}")
        for fk_name in fk_field_names:
            lines.append(f"    {fk_name}: Optional[int] = None")
        lines.append("")
        lines.append("")

        lines.append(f"class {cls}Update(SQLModel):")
        if not body and not fk_field_names:
            lines.append("    pass")
        for f in body:
            py_type = PY_TYPE_MAP.get(f.type, "str") if not f.is_reference else "int"
            if f.pattern:
                lines.append(
                    f'    {to_snake_case(f.name)}: Optional[{py_type}] = Field(default=None, pattern=r"{f.pattern}")'
                )
            else:
                lines.append(f"    {to_snake_case(f.name)}: Optional[{py_type}] = None")
        for fk_name in fk_field_names:
            lines.append(f"    {fk_name}: Optional[int] = None")
        lines.append("")
        lines.append("")

    return "\n".join(lines) + "\n"


