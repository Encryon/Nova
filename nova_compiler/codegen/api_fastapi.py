def _generate_router(
    entity: Entity,
    actions: list[str],
    protected_role: str | None = None,
    notify_actions: list[str] | None = None,
) -> str:
    cls = _model_class_name(entity)
    table = _table_name(entity)
    var = to_snake_case(entity.name)
    tag = entity.name
    notify_actions = notify_actions or []

    lines = [
        _HEADER,
        "from __future__ import annotations",
        "",
        "from fastapi import APIRouter, Depends, HTTPException",
        "from sqlmodel import Session, select",
        "",
        "from ..database import get_session",
        f"from ..models import {cls}, {cls}Create, {cls}Update",
    ]
    if protected_role:
        lines.append("from ..auth import require_role")
    if notify_actions:
        # `notifier: ...` sur `api {entity.name} { ... }` (nécessite un bloc
        # `email { ... }` — validé à la compilation, voir parser.py).
        lines.append("from ..emailer import send_email")
    lines.append("")
    router_kwargs = f'prefix="/{table}", tags=["{tag}"]'
    if protected_role:
        # `proteger: <role>` dans le DSL protège TOUTES les actions de cette
        # API d'un coup — le plus simple à écrire, et le plus dur à oublier.
        router_kwargs += f', dependencies=[Depends(require_role("{protected_role}"))]'
    lines += [
        f"router = APIRouter({router_kwargs})",
        "",
        "",
    ]

    if "list" in actions:
        lines += [
            f'@router.get("/", response_model=list[{cls}])',
            f"def list_{table}(session: Session = Depends(get_session)):",
            f'    """list / liste — retourne tous les {tag}."""',
            f"    return session.exec(select({cls})).all()",
            "",
            "",
        ]

    if "get" in actions:
        lines += [
            f'@router.get("/{{item_id}}", response_model={cls})',
            f"def get_{var}(item_id: int, session: Session = Depends(get_session)):",
            f'    """get / obtenir / lire — retourne un {tag} par id."""',
            f"    item = session.get({cls}, item_id)",
            "    if item is None:",
            f'        raise HTTPException(status_code=404, detail="{tag} not found")',
            "    return item",
            "",
            "",
        ]

    if "create" in actions:
        lines += [
            f'@router.post("/", response_model={cls}, status_code=201)',
            f"def create_{var}(payload: {cls}Create, session: Session = Depends(get_session)):",
            f'    """create / créer — crée un nouveau {tag}."""',
            f"    item = {cls}.model_validate(payload)",
            "    session.add(item)",
            "    session.commit()",
            "    session.refresh(item)",
        ]
        if "create" in notify_actions:
            lines.append(
                f'    send_email(subject="[NOVA] Nouveau {tag} / New {tag}", '
                f'body=f"{tag} #{{item.id}} créé / created.")'
            )
        lines += [
            "    return item",
            "",
            "",
        ]

    if "update" in actions:
        lines += [
            f'@router.put("/{{item_id}}", response_model={cls})',
            f"def update_{var}(item_id: int, payload: {cls}Update, session: Session = Depends(get_session)):",
            f'    """update / modifier — met à jour un {tag} existant."""',
            f"    item = session.get({cls}, item_id)",
            "    if item is None:",
            f'        raise HTTPException(status_code=404, detail="{tag} not found")',
            "    for key, value in payload.model_dump(exclude_unset=True).items():",
            "        setattr(item, key, value)",
            "    session.add(item)",
            "    session.commit()",
            "    session.refresh(item)",
        ]
        if "update" in notify_actions:
            lines.append(
                f'    send_email(subject="[NOVA] {tag} modifié / updated", '
                f'body=f"{tag} #{{item.id}} mis à jour / updated.")'
            )
        lines += [
            "    return item",
            "",
            "",
        ]

    if "delete" in actions:
        lines += [
            f'@router.delete("/{{item_id}}", status_code=204)',
            f"def delete_{var}(item_id: int, session: Session = Depends(get_session)):",
            f'    """delete / supprimer — supprime un {tag}."""',
            f"    item = session.get({cls}, item_id)",
            "    if item is None:",
            f'        raise HTTPException(status_code=404, detail="{tag} not found")',
        ]
        if "delete" in notify_actions:
            # L'id est capturé avant `session.delete`/`commit` : l'objet est
            # expiré après le commit, `item.id` ne serait plus fiable ensuite.
            lines.append("    deleted_id = item.id")
        lines += [
            "    session.delete(item)",
            "    session.commit()",
        ]
        if "delete" in notify_actions:
            lines.append(
                f'    send_email(subject="[NOVA] {tag} supprimé / deleted", '
                f'body=f"{tag} #{{deleted_id}} supprimé / deleted.")'
            )
        lines += [
            "    return None",
            "",
        ]

    return "\n".join(lines) + "\n"


def _generate_main(program: NovaProgram) -> str:
    app_name = program.app.name if program.app else "NovaApp"
    has_auth = program.auth is not None and program.auth.enabled
    has_queries = bool(program.queries)
    has_uploads = _has_uploads(program)
    lines = [
        _HEADER,
        "from __future__ import annotations",
        "",
        "import importlib",
        "import pkgutil",
        "",
        "from fastapi import FastAPI",
        "from fastapi.middleware.cors import CORSMiddleware",
    ]
    if has_uploads:
        lines.append("from fastapi.staticfiles import StaticFiles")
    lines += [
        "",
        "from .database import init_db",
        "from . import routers_custom",
    ]
    if has_auth:
        lines.append("from .auth import router as auth_router")
    if has_queries:
        lines.append("from .routers._requetes import router as requetes_router")
    if has_uploads:
        lines.append("from .routers._uploads import router as uploads_router, UPLOADS_DIR")
    for api in program.apis:
        entity = program.get_entity(api.entity)
        if entity is None:
            continue
        table = _table_name(entity)
        lines.append(f"from .routers.{table} import router as {table}_router")
    lines += [
        "",
        f'app = FastAPI(title="{app_name}", description="Généré par NOVA / Generated by NOVA")',
        "",
        "app.add_middleware(",
        "    CORSMiddleware,",
        '    allow_origins=["*"],',
        "    allow_methods=[\"*\"],",
        "    allow_headers=[\"*\"],",
        ")",
        "",
        "",
        "@app.on_event(\"startup\")",
        "def on_startup() -> None:",
        "    init_db()",
        "",
        "",
    ]
    if has_uploads:
        # Chemin distinct de "/uploads" (le routeur POST ci-dessous) pour
        # éviter tout conflit de préfixe entre le Mount ASGI (fichiers
        # statiques, GET) et l'APIRouter (upload, POST).
        lines.append('app.mount("/files", StaticFiles(directory=str(UPLOADS_DIR)), name="files")')
    if has_auth:
        lines.append("app.include_router(auth_router)")
    if has_queries:
        lines.append("app.include_router(requetes_router)")
    if has_uploads:
        lines.append("app.include_router(uploads_router)")
    for api in program.apis:
        entity = program.get_entity(api.entity)
        if entity is None:
            continue
        table = _table_name(entity)
        lines.append(f"app.include_router({table}_router)")
    lines += [
        "",
        "# Logique métier hors DSL (validations avancées, requêtes complexes,",
        "# écritures en base sur mesure...) : tout module de app/routers_custom/",
        "# exposant une variable `router` est inclus automatiquement. Ce dossier",
        "# n'est jamais régénéré par `nova compile` — voir routers_custom/example.py.",
        "for _finder, _mod_name, _ispkg in pkgutil.iter_modules(routers_custom.__path__):",
        '    _custom_mod = importlib.import_module(f".routers_custom.{_mod_name}", package=__package__)',
        '    if hasattr(_custom_mod, "router"):',
        "        app.include_router(_custom_mod.router)",
        "",
        "",
        '@app.get("/health")',
        "def health():",
        '    return {"status": "ok"}',
        "",
    ]
    return "\n".join(lines) + "\n"


def _generate_auth(program: NovaProgram) -> str:
    auth = program.auth
    roles = auth.roles if auth and auth.roles else ["user"]
    default_role = auth.default_role if auth else "user"
    roles_literal = "[" + ", ".join(repr(r) for r in roles) + "]"
    return _HEADER + f'''
from __future__ import annotations

import os
from datetime import datetime, timedelta, timezone
from typing import Optional

import bcrypt
from fastapi import APIRouter, Depends, HTTPException, status
from fastapi.security import OAuth2PasswordBearer, OAuth2PasswordRequestForm
from jose import JWTError, jwt
from sqlmodel import Field, Session, SQLModel, select

from .database import get_session

# Bloc `auth {{ ... }}` du fichier .nova : rôles déclarés et rôle par défaut
# attribué à l'inscription si aucun n'est précisé.
ROLES = {roles_literal}
DEFAULT_ROLE = "{default_role}"

# Clé de signature JWT : à définir en production via la variable
# d'environnement NOVA_JWT_SECRET. La valeur par défaut ci-dessous permet au
# projet généré de démarrer "out of the box" — ne JAMAIS l'utiliser telle
# quelle en production.
SECRET_KEY = os.environ.get("NOVA_JWT_SECRET", "nova-dev-secret-change-me")
ALGORITHM = "HS256"
ACCESS_TOKEN_EXPIRE_MINUTES = 60 * 24

# Hachage direct via la bibliothèque `bcrypt` (et non `passlib`, dont
# l'intégration bcrypt est cassée avec les versions récentes de la
# bibliothèque `bcrypt` — `passlib`, non maintenu depuis 2020, échoue avec
# une `ValueError` sans rapport à l'exécution — voir la doc du framework).
oauth2_scheme = OAuth2PasswordBearer(tokenUrl="/auth/login", auto_error=False)


class User(SQLModel, table=True):
    """Table utilisateur générée par le bloc `auth {{ ... }}` — indépendante
    des entités du DSL."""

    __tablename__ = "nova_users"

    id: Optional[int] = Field(default=None, primary_key=True)
    email: str = Field(unique=True, index=True)
    password_hash: str
    role: str = Field(default=DEFAULT_ROLE)
    created_at: datetime = Field(default_factory=datetime.utcnow)


class UserCreate(SQLModel):
    email: str
    password: str
    role: Optional[str] = None


class UserRead(SQLModel):
    id: int
    email: str
    role: str


def hash_password(password: str) -> str:
    return bcrypt.hashpw(password.encode("utf-8"), bcrypt.gensalt()).decode("utf-8")


def verify_password(password: str, password_hash: str) -> bool:
    return bcrypt.checkpw(password.encode("utf-8"), password_hash.encode("utf-8"))


def create_access_token(data: dict) -> str:
    to_encode = data.copy()
    expire = datetime.now(timezone.utc) + timedelta(minutes=ACCESS_TOKEN_EXPIRE_MINUTES)
    to_encode.update({{"exp": expire}})
    return jwt.encode(to_encode, SECRET_KEY, algorithm=ALGORITHM)


def get_current_user(
    token: Optional[str] = Depends(oauth2_scheme), session: Session = Depends(get_session)
) -> User:
    credentials_error = HTTPException(
        status_code=status.HTTP_401_UNAUTHORIZED,
        detail="Identifiants invalides ou absents / Missing or invalid credentials",
        headers={{"WWW-Authenticate": "Bearer"}},
    )
    if token is None:
        raise credentials_error
    try:
        payload = jwt.decode(token, SECRET_KEY, algorithms=[ALGORITHM])
        email = payload.get("sub")
        if email is None:
            raise credentials_error
    except JWTError:
        raise credentials_error
    user = session.exec(select(User).where(User.email == email)).first()
    if user is None:
        raise credentials_error
    return user


def require_role(role: str):
    """Dépendance FastAPI protégeant une route/un routeur pour un rôle donné
    (utilisée automatiquement pour `api Xxx {{ ... proteger: <role> }}`) —
    un utilisateur "admin" passe toujours, quel que soit le rôle requis."""

    def _dependency(user: User = Depends(get_current_user)) -> User:
        if user.role != role and user.role != "admin":
            raise HTTPException(status_code=status.HTTP_403_FORBIDDEN, detail="Accès refusé / Forbidden")
        return user

    return _dependency


router = APIRouter(prefix="/auth", tags=["auth"])


@router.post("/register", response_model=UserRead, status_code=201)
def register(payload: UserCreate, session: Session = Depends(get_session)):
    existing = session.exec(select(User).where(User.email == payload.email)).first()
    if existing is not None:
        raise HTTPException(status_code=400, detail="Email déjà utilisé / Email already registered")
    role = payload.role if payload.role in ROLES else DEFAULT_ROLE
    user = User(email=payload.email, password_hash=hash_password(payload.password), role=role)
    session.add(user)
    session.commit()
    session.refresh(user)
    return user


@router.post("/login")
def login(form_data: OAuth2PasswordRequestForm = Depends(), session: Session = Depends(get_session)):
    """Compatible OAuth2PasswordRequestForm : envoyer `username` (= email) et
    `password` en `application/x-www-form-urlencoded`."""
    user = session.exec(select(User).where(User.email == form_data.username)).first()
    if user is None or not verify_password(form_data.password, user.password_hash):
        raise HTTPException(status_code=401, detail="Identifiants invalides / Invalid credentials")
    token = create_access_token({{"sub": user.email, "role": user.role}})
    return {{"access_token": token, "token_type": "bearer"}}


@router.get("/me", response_model=UserRead)
def me(user: User = Depends(get_current_user)):
    return user
'''


def _format_query_value(value) -> str:
    if isinstance(value, str):
        return repr(value)
    return repr(value)


def _generate_query_router(program: NovaProgram) -> str:
    lines = [
        _HEADER,
        "from __future__ import annotations",
        "",
        "from fastapi import APIRouter, Depends",
        "from sqlmodel import Session, select",
        "",
        "from ..database import get_session",
        "from .. import models",
        "",
        'router = APIRouter(prefix="/requetes", tags=["requetes"])',
        "",
        "",
    ]
    for q in program.queries:
        entity = program.get_entity(q.entity)
        cls = to_pascal_case(entity.name) if entity else to_pascal_case(q.entity)
        slug = to_snake_case(q.name).replace("_", "-")
        fn_name = to_snake_case(q.name)
        lines += [
            f'@router.get("/{slug}", response_model=list[models.{cls}])',
            f"def {fn_name}(session: Session = Depends(get_session)):",
            f'    """Requête déclarative `requete {q.name} sur {q.entity} {{ ... }}` du fichier .nova."""',
            f"    query = select(models.{cls})",
        ]
        for f in q.filters:
            snake = to_snake_case(f.field)
            lines.append(f"    query = query.where(models.{cls}.{snake} {f.op} {_format_query_value(f.value)})")
        if q.order_by:
            snake = to_snake_case(q.order_by)
            direction = "desc" if q.order_dir == "desc" else "asc"
            lines.append(f"    query = query.order_by(models.{cls}.{snake}.{direction}())")
        if q.limit is not None:
            lines.append(f"    query = query.limit({q.limit})")
        lines += [
            "    return session.exec(query).all()",
            "",
            "",
        ]
    return "\n".join(lines) + "\n"


