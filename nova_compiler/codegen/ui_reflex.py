def _wrap_page_body(inner_component_src: str, on_mount_expr: str, container_max_width: str) -> str:
    """Enveloppe le contenu propre à une page (`inner_component_src`, une
    expression Reflex sans le mot-clé `return`) dans le "shell" commun à
    toutes les pages : barre de navigation, conteneur centré, fond pleine
    page. Cette fonction gère l'indentation pour que le fichier généré
    reste lisible ; Python n'exige pas d'indentation précise à l'intérieur
    d'une liste d'arguments entre parenthèses, donc une légère imprécision
    ne casserait rien, mais on la soigne pour un fichier généré agréable à
    relire."""
    indented_inner = textwrap.indent(inner_component_src.rstrip("\n"), "            ")
    return (
        "    return rx.box(\n"
        "        nova_navbar(),\n"
        "        rx.container(\n"
        f"{indented_inner},\n"
        f'            max_width="{container_max_width}",\n'
        '            padding="2em",\n'
        '            width="100%",\n'
        "        ),\n"
        f"        on_mount={on_mount_expr},\n"
        '        width="100%",\n'
        '        min_height="100vh",\n'
        '        background="var(--gray-2)",\n'
        "    )\n"
    )


def _generate_state_and_view(page: Page, program: NovaProgram, has_auth: bool) -> tuple[str, str]:
    """Retourne (code_du_state, code_de_la_fonction_de_page) pour un bloc page."""
    if not page.shows:
        state_cls = _state_class_name(page)
        state_code = f"class {state_cls}(rx.State):\n    pass\n"
        view_code = (
            f"def {to_snake_case(page.name)}_page() -> rx.Component:\n"
            + _wrap_page_body(f'rx.heading("{page.name}", size="7")', "None", "800px")
        )
        return state_code, view_code

    show = page.shows[0]  # MVP : une entité principale par page
    entity = program.get_entity(show.entity)
    state_cls = _state_class_name(page)
    table_url_path = to_snake_case(pluralize(to_ascii_identifier(show.entity)))
    title_expr = _title_expr_src(show, page.name)
    fields = entity.fields if entity else []
    api = _api_for_entity(program, show.entity)
    is_protected = bool(has_auth and api and api.protected_role)

    state_lines = [
        f"class {state_cls}(rx.State):",
        f'    """État Reflex pour la page `{page.name}` (affiche {show.entity} en mode {show.mode}).'
        + (' Route protégée : le jeton AuthState est envoyé en en-tête Authorization."""' if is_protected else '"""'),
        "    rows: list[dict] = []",
        "    is_loading: bool = False",
    ]
    for f in fields:
        snake = to_snake_case(f.name)
        if f.multilingual:
            for lang in LANG_CODES:
                state_lines.append(f'    new_{snake}_{lang}: str = ""')
        else:
            state_lines.append(f'    new_{snake}: str = ""')

    if show.mode == "form":
        # Setters explicites : ne pas compter sur les setters `set_<var>`
        # auto-générés par Reflex, dont la disponibilité/le nom exact a varié
        # selon les versions de Reflex (observé en pratique : AttributeError
        # "has no attribute 'set_new_xxx'" avec certaines versions récentes).
        # Un setter écrit explicitement fonctionne quelle que soit la version.
        for f in fields:
            snake = to_snake_case(f.name)
            if f.multilingual:
                for lang in LANG_CODES:
                    state_lines.append(f"    def set_new_{snake}_{lang}(self, value: str) -> None:")
                    state_lines.append(f"        self.new_{snake}_{lang} = value")
            else:
                state_lines.append(f"    def set_new_{snake}(self, value: str) -> None:")
                state_lines.append(f"        self.new_{snake} = value")
        # Champs `file`/`image` : pas de setter texte, un gestionnaire
        # d'upload à la place (voir `_upload_handler_state_lines`).
        for f in fields:
            if f.type in _UPLOAD_FIELD_TYPES:
                state_lines += _upload_handler_state_lines(state_cls, f)

    auth_header_lines = []
    if is_protected:
        auth_header_lines = [
            "        auth_state = await self.get_state(AuthState)",
            '        headers = {"Authorization": f"Bearer {auth_state.token}"} if auth_state.token else {}',
        ]
    headers_kwarg = ", headers=headers" if is_protected else ""

    state_lines += [
        "",
        "    async def load_rows(self):",
        "        self.is_loading = True",
    ]
    state_lines += auth_header_lines
    state_lines += [
        "        async with httpx.AsyncClient() as client:",
        f'            resp = await client.get(f"{{BACKEND_URL}}/{table_url_path}/"{headers_kwarg})',
        "            if resp.status_code == 200:",
        "                self.rows = resp.json()",
        "        self.is_loading = False",
        "",
    ]
    if show.mode == "form":
        payload_parts = []
        for f in fields:
            snake = to_snake_case(f.name)
            if f.multilingual:
                payload_parts += [f'"{snake}_{lang}": self.new_{snake}_{lang}' for lang in LANG_CODES]
            else:
                payload_parts.append(f'"{snake}": self.new_{snake}')
        payload_items = ", ".join(payload_parts)
        redirect_route = _table_route_for_entity(program, show.entity)
        state_lines += ["    async def submit(self):"]
        state_lines += auth_header_lines
        state_lines += [
            "        async with httpx.AsyncClient() as client:",
            f'            await client.post(f"{{BACKEND_URL}}/{table_url_path}/", json={{{payload_items}}}{headers_kwarg})',
        ]
        for f in fields:
            snake = to_snake_case(f.name)
            if f.multilingual:
                for lang in LANG_CODES:
                    state_lines.append(f'        self.new_{snake}_{lang} = ""')
            else:
                state_lines.append(f'        self.new_{snake} = ""')
        if redirect_route:
            # On revient sur le tableau qui liste cette entité une fois
            # l'enregistrement créé, plutôt que de rester sur le formulaire.
            state_lines.append(f'        return rx.redirect("{redirect_route}")')
        else:
            state_lines.append("        await self.load_rows()")
        state_lines.append("")
    state_code = "\n".join(state_lines) + "\n"

    style_kwargs = _style_kwargs_src(show.style)

    # ---- vue -------------------------------------------------------------
    if show.mode == "table":
        header_cells = ", ".join(f'rx.table.column_header_cell("{f.name}")' for f in fields)

        def _table_cell_src(f) -> str:
            if f.multilingual:
                return f"rx.table.cell({_multilingual_display_expr(f)})"
            access = f"row['{to_snake_case(f.name)}']"
            return f"rx.table.cell({_field_value_src(f, access, access)})"

        row_cells = ", ".join(_table_cell_src(f) for f in fields)
        create_page = _form_page_for_entity(program, show.entity)
        create_link = (
            f'rx.link(rx.button("+ {create_page.name}", size="2"), href="{_page_route(create_page)}"),'
            if create_page
            else ""
        )
        inner = (
            "rx.vstack(\n"
            "    rx.hstack(\n"
            f'        rx.heading({title_expr}, size="7"),\n'
            "        rx.spacer(),\n"
            f"        {create_link}\n"
            '        width="100%",\n'
            '        align="center",\n'
            "    ),\n"
            "    rx.card(\n"
            "        rx.table.root(\n"
            "            rx.table.header(\n"
            f"                rx.table.row({header_cells}),\n"
            "            ),\n"
            "            rx.table.body(\n"
            f"                rx.foreach({state_cls}.rows, lambda row: rx.table.row({row_cells})),\n"
            "            ),\n"
            '            variant="surface",\n'
            '            width="100%",\n'
            "        ),\n"
            f'        width="100%"{style_kwargs},\n'
            "    ),\n"
            '    spacing="4",\n'
            '    width="100%",\n'
            ")"
        )
        container_width = "1100px"
    elif show.mode == "form":
        field_blocks = []
        for f in fields:
            snake = to_snake_case(f.name)
            if f.multilingual:
                field_blocks.append(_multilingual_form_block_src(state_cls, f))
                continue
            if f.type in _UPLOAD_FIELD_TYPES:
                field_blocks.append(_upload_form_block_src(state_cls, f))
                continue
            input_type, extra_kwarg = _input_type_and_extra_kwarg(f)
            type_kwarg = f', type="{input_type}"' if input_type != "text" else ""
            field_blocks.append(
                "    rx.vstack(\n"
                f'        rx.text("{f.name}", size="2", weight="bold", color_scheme="gray"),\n'
                f'        rx.input(placeholder="{f.name}", value={state_cls}.new_{snake}, '
                f"on_change={state_cls}.set_new_{snake}, size=\"3\", width=\"100%\"{type_kwarg}{extra_kwarg}),\n"
                '        spacing="1",\n'
                '        width="100%",\n'
                "    ),"
            )
        fields_src = "\n".join(field_blocks)
        inner = (
            "rx.card(\n"
            "    rx.vstack(\n"
            f'        rx.heading({title_expr}, size="7"),\n'
            f"{fields_src}\n"
            f'        rx.button("Enregistrer / Save", on_click={state_cls}.submit, size="3", '
            'width="100%", color_scheme="violet"),\n'
            '        spacing="4",\n'
            '        width="100%",\n'
            "    ),\n"
            f'    padding="2em",\n'
            f'    width="100%"{style_kwargs},\n'
            ")"
        )
        container_width = "560px"
    else:  # card

        def _card_value_src(f) -> str:
            if f.multilingual:
                return f"rx.text({_multilingual_display_expr(f)})"
            access = f"row['{to_snake_case(f.name)}']"
            default_src = f'rx.text(f"{f.name}: {{{access}}}")'
            return _field_value_src(f, access, default_src)

        card_rows = ", ".join(_card_value_src(f) for f in fields)
        inner = (
            "rx.vstack(\n"
            f'    rx.heading({title_expr}, size="7"),\n'
            "    rx.grid(\n"
            f"        rx.foreach({state_cls}.rows, lambda row: rx.card(\n"
            f"            rx.vstack({card_rows}, spacing=\"2\"),\n"
            '            padding="1.5em",\n'
            "        )),\n"
            '        columns="3",\n'
            '        spacing="4",\n'
            '        width="100%",\n'
            "    ),\n"
            '    spacing="4",\n'
            f'    width="100%"{style_kwargs},\n'
            ")"
        )
        container_width = "1100px"

    view_code = (
        f"def {to_snake_case(page.name)}_page() -> rx.Component:\n"
        + _wrap_page_body(inner, f"{state_cls}.load_rows", container_width)
    )
    return state_code, view_code


