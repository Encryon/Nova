_WEEKDAY_LABELS = ["Lun/Mon", "Mar/Tue", "Mer/Wed", "Jeu/Thu", "Ven/Fri", "Sam/Sat", "Dim/Sun"]


def _calendar_state_class_name(cal: Calendar) -> str:
    return f"{to_pascal_case(cal.name)}CalendarState"


def _calendar_route(cal: Calendar) -> str:
    slug = to_snake_case(to_ascii_identifier(cal.name)).replace("_", "-")
    return f"/calendriers/{slug}" if slug else "/calendriers"


def _calendar_data_source(program: NovaProgram, cal: Calendar, has_auth: bool) -> tuple[str, bool]:
    """Résout `calendar ... sur <Entite>` en (chemin_url_backend, protege) —
    toujours une Entity ici (`parser._validate_calendars` le garantit déjà),
    même logique d'héritage de la protection `api <Entity> { proteger: ... }`
    que `_chart_data_source`."""
    url_path = to_snake_case(pluralize(to_ascii_identifier(cal.entity))) + "/"
    api = _api_for_entity(program, cal.entity)
    is_protected = bool(has_auth and api and api.protected_role)
    return url_path, is_protected


def _generate_calendar_state_and_view(cal: Calendar, program: NovaProgram, has_auth: bool) -> tuple[str, str]:
    """Retourne (code_du_state, code_de_la_fonction_de_page) pour un bloc
    `calendar` : un état Reflex qui charge TOUTES les lignes de l'entité
    (comme une page table) puis les regroupe côté serveur, jour par jour du
    mois affiché, via `_build_days` (stdlib `calendar.Calendar.
    monthdatescalendar` + `datetime.date` — aucune dépendance JS
    supplémentaire, conformément au choix de conception retenu pour cette
    fonctionnalité). Chaque jour est un dict PLAT (`date`, `day`,
    `in_month`, `events_text`) plutôt qu'un dict contenant une liste
    imbriquée d'événements : `rx.foreach` niché sur une valeur `list[str]`
    à l'intérieur d'un state var `list[dict]` lève `ForeachVarError` (bug
    réel rencontré et corrigé pendant la conception de ce bloc `calendar`,
    voir exploration précédente) — d'où `events_text`, les titres des
    événements du jour déjà joints en une seule chaîne."""
    state_cls = _calendar_state_class_name(cal)
    url_path, is_protected = _calendar_data_source(program, cal, has_auth)
    date_field_snake = to_snake_case(cal.date_field)
    title_field_snake = to_snake_case(cal.title_field) if cal.title_field else None

    auth_header_lines = []
    if is_protected:
        auth_header_lines = [
            "        auth_state = await self.get_state(AuthState)",
            '        headers = {"Authorization": f"Bearer {auth_state.token}"} if auth_state.token else {}',
        ]
    headers_kwarg = ", headers=headers" if is_protected else ""

    # Sans `champ_titre`/`title_field`, on affiche un simple marqueur "•"
    # pour signaler qu'un jour a des enregistrements, plutôt que rien.
    title_expr = f'str(row.get("{title_field_snake}", ""))' if title_field_snake else '"•"'

    state_lines = [
        f"class {state_cls}(rx.State):",
        f'    """État Reflex pour le calendrier `{cal.name}` (source : {cal.entity}).'
        + (' Route protégée : le jeton AuthState est envoyé en en-tête Authorization."""' if is_protected else '"""'),
        "    rows: list[dict] = []",
        "    days: list[dict] = []",
        "    year: int = date.today().year",
        "    month: int = date.today().month",
        '    label: str = ""',
        "    is_loading: bool = False",
        "",
        "    async def load_rows(self):",
        "        self.is_loading = True",
    ]
    state_lines += auth_header_lines
    state_lines += [
        "        async with httpx.AsyncClient() as client:",
        f'            resp = await client.get(f"{{BACKEND_URL}}/{url_path}"{headers_kwarg})',
        "            if resp.status_code == 200:",
        "                self.rows = resp.json()",
        "        self.is_loading = False",
        "        self._build_days()",
        "",
        "    def _build_days(self):",
        '        self.label = f"{self.year}-{self.month:02d}"',
        "        weeks = calendar.Calendar(firstweekday=0).monthdatescalendar(self.year, self.month)",
        "        days = []",
        "        for week in weeks:",
        "            for d in week:",
        "                iso = d.isoformat()",
        '                events_text = ", ".join(',
        f"                    {title_expr}",
        "                    for row in self.rows",
        f'                    if str(row.get("{date_field_snake}", ""))[:10] == iso',
        "                )",
        "                days.append({",
        '                    "date": iso,',
        '                    "day": d.day,',
        '                    "in_month": d.month == self.month,',
        '                    "events_text": events_text,',
        "                })",
        "        self.days = days",
        "",
        "    def prev_month(self):",
        "        self.month -= 1",
        "        if self.month < 1:",
        "            self.month = 12",
        "            self.year -= 1",
        "        self._build_days()",
        "",
        "    def next_month(self):",
        "        self.month += 1",
        "        if self.month > 12:",
        "            self.month = 1",
        "            self.year += 1",
        "        self._build_days()",
        "",
    ]
    state_code = "\n".join(state_lines) + "\n"

    weekday_header = ",\n        ".join(
        f'rx.text("{label}", size="2", weight="bold", align="center")' for label in _WEEKDAY_LABELS
    )
    day_cell = (
        "rx.box(\n"
        '            rx.text(day["day"], size="2", weight="bold"),\n'
        '            rx.cond(day["events_text"] != "", rx.text(day["events_text"], size="1", color_scheme="gray")),\n'
        '            opacity=rx.cond(day["in_month"], "1", "0.35"),\n'
        '            padding="0.5em",\n'
        '            border="1px solid var(--gray-5)",\n'
        '            min_height="80px",\n'
        '            width="100%",\n'
        "        )"
    )
    inner = (
        "rx.vstack(\n"
        f'    rx.heading("{cal.name}", size="7"),\n'
        "    rx.hstack(\n"
        f'        rx.button("<", on_click={state_cls}.prev_month, size="2", variant="soft"),\n'
        f'        rx.heading({state_cls}.label, size="4"),\n'
        f'        rx.button(">", on_click={state_cls}.next_month, size="2", variant="soft"),\n'
        '        spacing="3",\n'
        '        align="center",\n'
        "    ),\n"
        "    rx.grid(\n"
        f"        {weekday_header},\n"
        '        columns="7",\n'
        '        spacing="1",\n'
        '        width="100%",\n'
        "    ),\n"
        "    rx.grid(\n"
        f"        rx.foreach({state_cls}.days, lambda day: {day_cell}),\n"
        '        columns="7",\n'
        '        spacing="1",\n'
        '        width="100%",\n'
        "    ),\n"
        '    spacing="4",\n'
        '    width="100%",\n'
        ")"
    )
    view_code = (
        f"def {to_snake_case(cal.name)}_calendar_page() -> rx.Component:\n"
        + _wrap_page_body(inner, f"{state_cls}.load_rows", "1000px")
    )
    return state_code, view_code


# ---------------------------------------- champs riches (file/image/color/bool) ---
# Un champ `file`/`fichier`, `image`, `color`/`couleur` ou `bool` mérite un
# widget dédié plutôt qu'un `rx.input` texte générique : upload avec aperçu,
# sélecteur de couleur natif, badge Oui/Non. Ces helpers centralisent ce
# choix pour le formulaire (widget de saisie) et pour les vues table/card
# (rendu de valeur) afin que les deux restent cohérents.

_UPLOAD_FIELD_TYPES = ("file", "image")


def _input_type_and_extra_kwarg(f) -> tuple[str, str]:
    """Type HTML natif (`type="..."`) et kwarg Reflex additionnel pour un
    champ scalaire simple (pas file/image, gérés à part avec `rx.upload`) —
    donne un vrai sélecteur de date/heure/couleur/nombre au lieu d'un champ
    texte brut, sans changer le type de la variable de state (toujours
    `str`, comme avant) ni le format de la charge utile envoyée au backend."""
    if f.type == "date":
        return "date", ""
    if f.type == "datetime":
        return "datetime-local", ""
    if f.type == "int":
        return "number", ""
    if f.type == "float":
        return "number", ', step="any"'
    if f.type == "color":
        return "color", ""
    return "text", ""


def _upload_id(state_cls: str, field_snake: str) -> str:
    return f"upload_{to_snake_case(state_cls)}_{field_snake}"


def _upload_form_block_src(state_cls: str, f) -> str:
    """Bloc de formulaire pour un champ `file`/`image` : zone de dépôt
    (`rx.upload`) qui envoie le fichier au backend dès la sélection (voir
    `handle_upload_<champ>` généré dans le state) et stocke l'URL retournée
    dans `new_<champ>` — exactement comme les autres champs, qui portent
    déjà cette valeur au moment de la soumission du formulaire. Un aperçu
    (miniature pour une image, lien de téléchargement sinon) apparaît une
    fois l'upload terminé."""
    snake = to_snake_case(f.name)
    upload_id = _upload_id(state_cls, snake)
    var = f"{state_cls}.new_{snake}"
    if f.type == "image":
        preview = (
            f'rx.cond({var} != "", '
            f'rx.image(src=f"{{PUBLIC_BACKEND_URL}}{{{var}}}", width="80px", height="80px", '
            f'radius="md", style={{"object-fit": "cover"}})),'
        )
    else:
        preview = (
            f'rx.cond({var} != "", '
            f'rx.link({var}, href=f"{{PUBLIC_BACKEND_URL}}{{{var}}}", target="_blank", size="2")),'
        )
    dropzone_label = "Glisser un fichier ou cliquer / Drop a file or click"
    return (
        "    rx.vstack(\n"
        f'        rx.text("{f.name}", size="2", weight="bold", color_scheme="gray"),\n'
        "        rx.upload(\n"
        f'            rx.text("{dropzone_label}", size="2", color_scheme="gray"),\n'
        f'            id="{upload_id}",\n'
        f'            on_drop={state_cls}.handle_upload_{snake}(rx.upload_files(upload_id="{upload_id}")),\n'
        '            border="1px dashed var(--gray-8)",\n'
        '            border_radius="var(--radius-3)",\n'
        '            padding="1em",\n'
        '            width="100%",\n'
        "        ),\n"
        f"        {preview}\n"
        '        spacing="1",\n'
        '        width="100%",\n'
        "    ),"
    )


def _upload_handler_state_lines(state_cls: str, f) -> list[str]:
    """Méthode de state appelée dès qu'un fichier est déposé dans la zone
    d'upload : envoie le fichier au backend (`POST /uploads/`, voir
    codegen/api_fastapi._generate_uploads_router) et stocke l'URL relative
    retournée — la même variable `new_<champ>` que les autres types de
    champ, envoyée telle quelle dans la charge utile de `submit()`."""
    snake = to_snake_case(f.name)
    return [
        f"    async def handle_upload_{snake}(self, files: list[rx.UploadFile]) -> None:",
        "        for file in files:",
        "            data = await file.read()",
        "            async with httpx.AsyncClient() as client:",
        '                resp = await client.post(',
        '                    f"{BACKEND_URL}/uploads/", files={"file": (file.name, data)}',
        "                )",
        "                if resp.status_code == 200:",
        f'                    self.new_{snake} = resp.json()["url"]',
    ]


def _field_value_src(f, row_access: str, default_src: str) -> str:
    """Expression Reflex (texte source) affichant la valeur d'un champ `f`
    d'une ligne de données (`row_access`, ex. `row["prix"]`) dans une vue
    table/card. Rendu enrichi pour les types visuels ; `default_src` (fourni
    par l'appelant, différent entre table et card) pour tous les autres
    types — comportement inchangé par rapport à avant l'ajout des champs
    riches."""
    if f.type == "image":
        return (
            f'rx.cond({row_access} != "", '
            f'rx.image(src=f"{{PUBLIC_BACKEND_URL}}{{{row_access}}}", width="48px", height="48px", '
            f'radius="md", style={{"object-fit": "cover"}}), rx.text("—"))'
        )
    if f.type == "file":
        return (
            f'rx.cond({row_access} != "", '
            f'rx.link("Télécharger / Download", href=f"{{PUBLIC_BACKEND_URL}}{{{row_access}}}", target="_blank"), '
            f'rx.text("—"))'
        )
    if f.type == "color":
        return (
            f'rx.hstack(rx.box(width="16px", height="16px", background={row_access}, '
            f'border_radius="4px", border="1px solid var(--gray-6)"), rx.text({row_access}), '
            f'spacing="2", align="center")'
        )
    if f.type == "bool":
        return (
            f'rx.cond({row_access}, rx.badge("Oui / Yes", color_scheme="green"), '
            f'rx.badge("Non / No", color_scheme="gray"))'
        )
    return default_src


# ---------------------------------------------------------------- style ---

def _snake_to_camel(name: str) -> str:
    parts = name.replace("-", "_").split("_")
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:] if p)


def _style_kwargs_src(style: dict[str, str]) -> str:
    """Kwargs Reflex supplémentaires (`, class_name="...", style={...}`) pour
    un bloc `style { ... }` du DSL — chaîne vide si aucun style déclaré.
    Les clés connues de `keywords.STYLE_ALIASES` (ex. `couleur_fond`) sont
    traduites vers la propriété CSS réelle ; toute autre clé est passée
    telle quelle (snake_case ou kebab-case), convertie en camelCase pour
    Reflex — la "porte de sortie" qui garde ce bloc aussi souple que du CSS
    brut."""
    if not style:
        return ""
    class_name = None
    css_props: dict[str, str] = {}
    for key, value in style.items():
        if key in STYLE_CLASS_KEYS:
            class_name = value
            continue
        css_key = STYLE_ALIASES.get(key, key.replace("_", "-"))
        camel_key = _snake_to_camel(css_key.replace("-", "_"))
        css_props[camel_key] = value
    parts = []
    if class_name:
        parts.append(f'class_name="{class_name}"')
    if css_props:
        style_dict_src = ", ".join(f'"{k}": "{v}"' for k, v in css_props.items())
        parts.append(f"style={{{style_dict_src}}}")
    return (", " + ", ".join(parts)) if parts else ""


# ------------------------------------------------------------------ i18n ---
# Bloc `traductions { ... }` (textes d'interface) + modificateur
# `multilingue` sur un champ `chaine`/`texte` (données) : un état
# `LangState` partagé (langue courante persistée en cookie, comme
# `AuthState.token`), un sélecteur de langue dans la navbar, une fonction
# `t_<cle>()` par entrée du bloc `traductions`, et le rendu table/carte/
# formulaire des champs `multilingue`. Les textes/valeurs sont résolus via
# `rx.match(LangState.lang, ...)` — une expression Reflex RÉACTIVE — plutôt
# qu'un dict Python lu une fois à la génération : le texte affiché doit
# changer immédiatement quand on bascule la langue via le sélecteur, sans
# recharger la page.

_LANG_STATE_TEMPLATE = '''\
class LangState(rx.State):
    """État de langue partagé (voir bloc `traductions {{ ... }}` et le
    modificateur `multilingue` sur un champ) — persisté dans un cookie
    navigateur, valable entre deux rechargements de page, comme le jeton
    JWT de AuthState."""

    lang: str = rx.Cookie("fr", name="nova_lang")

    def set_lang(self, value: str) -> None:
        self.lang = value
'''


def _generate_lang_state() -> str:
    return _LANG_STATE_TEMPLATE


def _lang_switcher_src() -> str:
    return (
        "rx.select(\n"
        f"            {LANG_CODES!r},\n"
        "            value=LangState.lang,\n"
        "            on_change=LangState.set_lang,\n"
        '            size="2",\n'
        "        ),\n"
    )


def _translation_fn_name(key: str) -> str:
    return f"t_{to_snake_case(key)}"


def _generate_translation_helpers(program: NovaProgram) -> str:
    """Une fonction Python par clé du bloc `traductions`, retournant une
    expression `rx.match` réactive plutôt qu'un texte figé à la
    génération."""
    lines = []
    for key, texts in program.translations.items():
        fn_name = _translation_fn_name(key)
        cases = ", ".join(f"({lang!r}, {texts[lang]!r})" for lang in LANG_CODES)
        default = repr(texts["fr"])
        lines.append(f"def {fn_name}():")
        lines.append(f"    return rx.match(LangState.lang, {cases}, {default})")
        lines.append("")
        lines.append("")
    return "\n".join(lines)


def _title_expr_src(show, fallback: str) -> str:
    """Expression Reflex (texte source, sans le rendre entre guillemets)
    pour le titre d'une page : soit un appel à la fonction de traduction
    générée (`titre <cle>` -> `t_<cle>()`), soit une chaîne littérale
    entre guillemets (`titre "texte"`, ou titre absent -> nom de la
    page/du show, comportement inchangé par rapport à avant l'ajout de
    l'i18n)."""
    if show is not None and show.title_key:
        return f"{_translation_fn_name(show.title_key)}()"
    text = (show.title if show is not None else None) or fallback
    return f'"{text}"'


def _multilingual_display_expr(f, row_var: str = "row") -> str:
    """Expression Reflex affichant la valeur d'un champ `multilingue` dans
    la langue actuellement sélectionnée — une colonne par langue en base
    (voir codegen/api_fastapi.py), résolue avec `rx.match` (repli sur le
    français si `LangState.lang` ne correspondait à aucune des 6 valeurs
    attendues, ce qui ne devrait jamais arriver en pratique)."""
    base = to_snake_case(f.name)
    cases = ", ".join(f'("{lang}", {row_var}["{base}_{lang}"])' for lang in LANG_CODES)
    return f'rx.match(LangState.lang, {cases}, {row_var}["{base}_fr"])'


def _multilingual_form_block_src(state_cls: str, f) -> str:
    """Bloc de formulaire pour un champ `multilingue` : un `rx.input` par
    langue, labellisé `<champ> (fr)`/`<champ> (en)`/..., chacun lié à sa
    propre variable de state `new_<champ>_<lang>` — même pattern de
    setters explicites que les champs simples (voir
    `_generate_state_and_view`), pour la même raison (fiabilité variable
    des setters auto-générés selon la version de Reflex installée)."""
    base = to_snake_case(f.name)
    blocks = []
    for lang in LANG_CODES:
        var_name = f"new_{base}_{lang}"
        blocks.append(
            "    rx.vstack(\n"
            f'        rx.text("{f.name} ({lang})", size="2", weight="bold", color_scheme="gray"),\n'
            f'        rx.input(placeholder="{f.name} ({lang})", value={state_cls}.{var_name}, '
            f'on_change={state_cls}.set_{var_name}, size="3", width="100%"),\n'
            '        spacing="1",\n'
            '        width="100%",\n'
            "    ),"
        )
    return "\n".join(blocks)


