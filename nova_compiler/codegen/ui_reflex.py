"""
Générateur de frontend : AST NOVA -> application Reflex (Python -> React).

Un bloc `page` devient une page Reflex : `afficher/show <Entity> comme/as
table|form|card` choisit le composant généré. Les données sont chargées
depuis le backend FastAPI via httpx.

Le rendu s'appuie sur le thème Radix intégré à Reflex (`rx.theme`) pour un
look moderne par défaut (arrondis, espacements, palette cohérente) sans
CSS personnalisé à écrire : une barre de navigation partagée entre toutes
les pages, un conteneur centré, des cartes (`rx.card`) pour les
tableaux/formulaires/fiches, et des boutons de navigation entre les pages
liées à une même entité (ex. lien "+ Nouveau" depuis un tableau vers son
formulaire de création).
"""

from __future__ import annotations

import textwrap

from ..ast_nodes import NovaProgram, Page
from .utils import to_ascii_identifier, to_pascal_case, to_snake_case, pluralize

_HEADER = (
    "# " + "-" * 76 + "\n"
    "# Fichier généré automatiquement par le compilateur NOVA. Ne pas éditer\n"
    "# à la main : régénérez à partir du fichier .nova source (`nova compile`).\n"
    "# Auto-generated by the NOVA compiler. Do not edit by hand: regenerate\n"
    "# from the source .nova file (`nova compile`).\n"
    "# " + "-" * 76 + "\n"
)


def _app_pkg_name(program: NovaProgram) -> str:
    if program.app:
        return to_snake_case(to_ascii_identifier(program.app.name)) or "nova_app"
    return "nova_app"


def _state_class_name(page: Page) -> str:
    return f"{to_pascal_case(page.name)}State"


def _page_route(page: Page) -> str:
    slug = to_snake_case(to_ascii_identifier(page.name)).replace("_", "-")
    return f"/{slug}" if slug else "/"


def _table_route_for_entity(program: NovaProgram, entity_name: str) -> str | None:
    """Première page en mode table affichant cette entité (cible de redirection
    après création, et lien "+ Nouveau" depuis le tableau)."""
    for p in program.pages:
        if p.shows and p.shows[0].entity == entity_name and p.shows[0].mode == "table":
            return _page_route(p)
    return None


def _form_page_for_entity(program: NovaProgram, entity_name: str) -> Page | None:
    for p in program.pages:
        if p.shows and p.shows[0].entity == entity_name and p.shows[0].mode == "form":
            return p
    return None


def _generate_navbar(program: NovaProgram) -> str:
    app_title = program.app.name if program.app else "NOVA App"
    links = "\n".join(
        f'        rx.link("{p.name}", href="{_page_route(p)}", size="3", weight="medium", '
        f'color_scheme="gray", high_contrast=True),'
        for p in program.pages
    )
    return (
        "def nova_navbar() -> rx.Component:\n"
        '    """Barre de navigation partagée entre toutes les pages générées."""\n'
        "    return rx.hstack(\n"
        f'        rx.heading("{app_title}", size="5", weight="bold"),\n'
        "        rx.spacer(),\n"
        f"{links}\n"
        "        align=\"center\",\n"
        "        width=\"100%\",\n"
        "        padding=\"1em 2em\",\n"
        "        border_bottom=\"1px solid var(--gray-5)\",\n"
        "        background=\"var(--color-panel-solid)\",\n"
        "        position=\"sticky\",\n"
        "        top=\"0\",\n"
        "        z_index=\"10\",\n"
        "    )\n"
    )


def _wrap_page_body(inner_component_src: str, on_mount_expr: str, container_max_width: str) -> str:
    """Enveloppe le contenu propre à une page (`inner_component_src`, une
    expression Reflex sans le mot-clé `return`) dans le "shell" commun à
    toutes les pages : barre de navigation, conteneur centré, fond pleine
    page. Cette fonction gère l'indentation pour que le fichier généré
    reste lisible ; Python n'exige pas d'indentation précise à l'intérieur
    d'une liste d'arguments entre parenthèses, donc une légère imprécision
    ne casserait rien, mais on la soigne pour un fichier généré agréable à
    relire."""
    indented_inner = textwrap.indent(inner_component_src.rstrip("\n"), "            ")
    return (
        "    return rx.box(\n"
        "        nova_navbar(),\n"
        "        rx.container(\n"
        f"{indented_inner},\n"
        f'            max_width="{container_max_width}",\n'
        '            padding="2em",\n'
        '            width="100%",\n'
        "        ),\n"
        f"        on_mount={on_mount_expr},\n"
        '        width="100%",\n'
        '        min_height="100vh",\n'
        '        background="var(--gray-2)",\n'
        "    )\n"
    )


def _generate_state_and_view(page: Page, program: NovaProgram) -> tuple[str, str]:
    """Retourne (code_du_state, code_de_la_fonction_de_page) pour un bloc page."""
    if not page.shows:
        state_cls = _state_class_name(page)
        state_code = f"class {state_cls}(rx.State):\n    pass\n"
        view_code = (
            f"def {to_snake_case(page.name)}_page() -> rx.Component:\n"
            + _wrap_page_body(f'rx.heading("{page.name}", size="7")', "None", "800px")
        )
        return state_code, view_code

    show = page.shows[0]  # MVP : une entité principale par page
    entity = program.get_entity(show.entity)
    state_cls = _state_class_name(page)
    table_url_path = to_snake_case(pluralize(to_ascii_identifier(show.entity)))
    title = show.title or page.name
    fields = entity.fields if entity else []

    state_lines = [
        f"class {state_cls}(rx.State):",
        f'    """État Reflex pour la page `{page.name}` (affiche {show.entity} en mode {show.mode})."""',
        "    rows: list[dict] = []",
        "    is_loading: bool = False",
    ]
    for f in fields:
        state_lines.append(f'    new_{to_snake_case(f.name)}: str = ""')

    if show.mode == "form":
        # Setters explicites : ne pas compter sur les setters `set_<var>`
        # auto-générés par Reflex, dont la disponibilité/le nom exact a varié
        # selon les versions de Reflex (observé en pratique : AttributeError
        # "has no attribute 'set_new_xxx'" avec certaines versions récentes).
        # Un setter écrit explicitement fonctionne quelle que soit la version.
        for f in fields:
            snake = to_snake_case(f.name)
            state_lines.append(f"    def set_new_{snake}(self, value: str) -> None:")
            state_lines.append(f"        self.new_{snake} = value")

    state_lines += [
        "",
        "    async def load_rows(self):",
        "        self.is_loading = True",
        "        async with httpx.AsyncClient() as client:",
        f'            resp = await client.get(f"{{BACKEND_URL}}/{table_url_path}/")',
        "            if resp.status_code == 200:",
        "                self.rows = resp.json()",
        "        self.is_loading = False",
        "",
    ]
    if show.mode == "form":
        payload_items = ", ".join(f'"{to_snake_case(f.name)}": self.new_{to_snake_case(f.name)}' for f in fields)
        redirect_route = _table_route_for_entity(program, show.entity)
        state_lines += [
            "    async def submit(self):",
            "        async with httpx.AsyncClient() as client:",
            f'            await client.post(f"{{BACKEND_URL}}/{table_url_path}/", json={{{payload_items}}})',
        ]
        for f in fields:
            state_lines.append(f'        self.new_{to_snake_case(f.name)} = ""')
        if redirect_route:
            # On revient sur le tableau qui liste cette entité une fois
            # l'enregistrement créé, plutôt que de rester sur le formulaire.
            state_lines.append(f'        return rx.redirect("{redirect_route}")')
        else:
            state_lines.append("        await self.load_rows()")
        state_lines.append("")
    state_code = "\n".join(state_lines) + "\n"

    # ---- vue -------------------------------------------------------------
    if show.mode == "table":
        header_cells = ", ".join(f'rx.table.column_header_cell("{f.name}")' for f in fields)
        row_cells = ", ".join(f'rx.table.cell(row["{to_snake_case(f.name)}"])' for f in fields)
        create_page = _form_page_for_entity(program, show.entity)
        create_link = (
            f'rx.link(rx.button("+ {create_page.name}", size="2"), href="{_page_route(create_page)}"),'
            if create_page
            else ""
        )
        inner = (
            "rx.vstack(\n"
            "    rx.hstack(\n"
            f'        rx.heading("{title}", size="7"),\n'
            "        rx.spacer(),\n"
            f"        {create_link}\n"
            '        width="100%",\n'
            '        align="center",\n'
            "    ),\n"
            "    rx.card(\n"
            "        rx.table.root(\n"
            "            rx.table.header(\n"
            f"                rx.table.row({header_cells}),\n"
            "            ),\n"
            "            rx.table.body(\n"
            f"                rx.foreach({state_cls}.rows, lambda row: rx.table.row({row_cells})),\n"
            "            ),\n"
            '            variant="surface",\n'
            '            width="100%",\n'
            "        ),\n"
            '        width="100%",\n'
            "    ),\n"
            '    spacing="4",\n'
            '    width="100%",\n'
            ")"
        )
        container_width = "1100px"
    elif show.mode == "form":
        field_blocks = []
        for f in fields:
            snake = to_snake_case(f.name)
            field_blocks.append(
                "    rx.vstack(\n"
                f'        rx.text("{f.name}", size="2", weight="bold", color_scheme="gray"),\n'
                f'        rx.input(placeholder="{f.name}", value={state_cls}.new_{snake}, '
                f"on_change={state_cls}.set_new_{snake}, size=\"3\", width=\"100%\"),\n"
                '        spacing="1",\n'
                '        width="100%",\n'
                "    ),"
            )
        fields_src = "\n".join(field_blocks)
        inner = (
            "rx.card(\n"
            "    rx.vstack(\n"
            f'        rx.heading("{title}", size="7"),\n'
            f"{fields_src}\n"
            f'        rx.button("Enregistrer / Save", on_click={state_cls}.submit, size="3", '
            'width="100%", color_scheme="violet"),\n'
            '        spacing="4",\n'
            '        width="100%",\n'
            "    ),\n"
            '    padding="2em",\n'
            '    width="100%",\n'
            ")"
        )
        container_width = "560px"
    else:  # card
        card_rows = ", ".join(
            f'rx.text(f"{f.name}: {{row[\'{to_snake_case(f.name)}\']}}")' for f in fields
        )
        inner = (
            "rx.vstack(\n"
            f'    rx.heading("{title}", size="7"),\n'
            "    rx.grid(\n"
            f"        rx.foreach({state_cls}.rows, lambda row: rx.card(\n"
            f"            rx.vstack({card_rows}, spacing=\"2\"),\n"
            '            padding="1.5em",\n'
            "        )),\n"
            '        columns="3",\n'
            '        spacing="4",\n'
            '        width="100%",\n'
            "    ),\n"
            '    spacing="4",\n'
            '    width="100%",\n'
            ")"
        )
        container_width = "1100px"

    view_code = (
        f"def {to_snake_case(page.name)}_page() -> rx.Component:\n"
        + _wrap_page_body(inner, f"{state_cls}.load_rows", container_width)
    )
    return state_code, view_code


def generate_frontend(program: NovaProgram) -> dict[str, str]:
    pkg = _app_pkg_name(program)
    app_title = program.app.name if program.app else "NOVA App"

    lines = [
        _HEADER,
        "from __future__ import annotations",
        "",
        "import os",
        "",
        "import httpx",
        "import reflex as rx",
        "",
        'BACKEND_URL = os.environ.get("NOVA_BACKEND_URL", "http://localhost:8000")',
        "",
        "",
    ]

    if program.pages:
        lines.append(_generate_navbar(program))
        lines.append("")

    page_fns = []
    for page in program.pages:
        state_code, view_code = _generate_state_and_view(page, program)
        lines.append(state_code)
        lines.append("")
        lines.append(view_code)
        lines.append("")
        page_fns.append((to_snake_case(page.name) + "_page", _page_route(page), page.name))

    lines.append(
        'app = rx.App(theme=rx.theme(appearance="light", accent_color="violet", '
        'radius="large", scaling="100%"))'
    )
    for fn_name, route, title in page_fns:
        lines.append(f'app.add_page({fn_name}, route="{route}", title="{title}")')
    if not page_fns:
        lines.append("")
        lines.append('@rx.page(route="/")')
        lines.append("def index() -> rx.Component:")
        lines.append(f'    return rx.center(rx.heading("{app_title}"))')

    lines += [
        "",
        "# Pages/composants hors DSL (validation avancée, UI sur mesure...) :",
        "# custom.py n'est jamais régénéré par `nova compile` (créé une seule",
        "# fois s'il n'existe pas déjà) — voir sa fonction register(app).",
        "try:",
        "    from . import custom as _custom",
        "except ImportError:",
        "    _custom = None",
        'if _custom is not None and hasattr(_custom, "register"):',
        "    _custom.register(app)",
    ]

    main_code = "\n".join(lines) + "\n"

    rxconfig = (
        _HEADER
        + "import reflex as rx\n\n"
        + f'config = rx.Config(\n    app_name="{pkg}",\n)\n'
    )

    return {
        f"frontend/{pkg}/{pkg}.py": main_code,
        f"frontend/{pkg}/__init__.py": "",
        "frontend/rxconfig.py": rxconfig,
        "frontend/requirements.txt": "reflex>=0.5\nhttpx>=0.27\n",
    }


_CUSTOM_FRONTEND_EXAMPLE = '''\
"""
Extensions frontend "custom" (frontend/<app>/custom.py).

Ce fichier n'est JAMAIS régénéré par `nova compile` : créé une seule fois,
puis laissé intact à chaque compilation suivante — contrairement au fichier
principal (<app>.py), entièrement régénéré à chaque fois.

C'est ici qu'ajouter tout ce que le DSL NOVA ne couvre pas encore : contrôles
de formulaire avancés (validation côté client), composants sur mesure,
pages hors du modèle table/formulaire/fiche, appels à des API tierces...

`register(app)` est appelé automatiquement par le fichier principal généré,
juste après la création de `app = rx.App(...)` : ajoutez-y vos propres
`app.add_page(...)`.
"""

from __future__ import annotations

import reflex as rx


def register(app: rx.App) -> None:
    """Point d'entrée appelé automatiquement au démarrage de l'application."""
    # Exemple : une page 100% custom, hors du DSL NOVA.
    #
    # def about_page() -> rx.Component:
    #     return rx.center(rx.heading("À propos"))
    #
    # app.add_page(about_page, route="/about", title="About")
    pass
'''


def generate_frontend_scaffold(program: NovaProgram) -> dict[str, str]:
    """Fichier d'extension "custom" : créé une seule fois si absent, jamais
    réécrit par une compilation suivante (contrairement à `generate_frontend`,
    dont le contenu est toujours régénéré)."""
    pkg = _app_pkg_name(program)
    return {f"frontend/{pkg}/custom.py": _CUSTOM_FRONTEND_EXAMPLE}
